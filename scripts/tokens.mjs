import StyleDictionary from "style-dictionary";
import { readFile, writeFile } from "node:fs/promises";
const source = JSON.parse(
  await readFile("design-system/tokens/foundations.json", "utf8"),
);
if (
  Object.keys(source.light).sort().join() !==
  Object.keys(source.dark).sort().join()
)
  throw new Error("Theme roles must match");
const resolveColor = (token) =>
  typeof token.$value === "string"
    ? source.primitive[token.$value.slice(11, -1)].$value.components
    : token.$value.components;
const luminance = (components) =>
  components
    .map((v) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4))
    .reduce((sum, v, i) => sum + v * [0.2126, 0.7152, 0.0722][i], 0);
for (const mode of ["light", "dark"]) {
  for (const [foreground, background, minimum] of [
    ["text", "background", 4.5],
    ["muted", "background", 4.5],
    ["accent", "background", 4.5],
    ["button-text", "button", 4.5],
    ["button-text", "button-hover", 4.5],
    ["focus", "background", 3],
  ]) {
    const a = luminance(resolveColor(source[mode][foreground]));
    const b = luminance(resolveColor(source[mode][background]));
    if ((Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05) < minimum)
      throw new Error(
        `Insufficient contrast: ${mode} ${foreground}/${background}`,
      );
  }
}
const dictionary = new StyleDictionary({
  tokens: source,
  usesDtcg: true,
  platforms: { css: { transformGroup: "css" } },
});
const platform = await dictionary.getPlatformTokens("css");
const values = Object.fromEntries(
  platform.allTokens.map((t) => [t.path.join("."), t.$value ?? t.value]),
);
const declarations = (mode) =>
  Object.entries(values)
    .filter(([k]) => k.startsWith(mode + "."))
    .map(
      ([k, v]) => `  --${k.slice(mode.length + 1).replaceAll(".", "-")}: ${v};`,
    )
    .join("\n");
const names = platform.allTokens.map((t) => t.path.join("-"));
if (new Set(names).size !== names.length)
  throw new Error("Token name collision");
const light = declarations("light") + "\n  color-scheme: light;";
const dark = declarations("dark") + "\n  color-scheme: dark;";
const css = `/* Generated by scripts/tokens.mjs. Edit design-system/tokens instead. */\n:root {\n${light}\n${declarations("space").replaceAll("--", "--space-")}\n${declarations("layout").replaceAll("--", "--layout-")}\n${declarations("type").replaceAll("--", "--type-")}\n}\n:root[data-theme="dark"] {\n${dark}\n}\n@media screen and (prefers-color-scheme: dark) {\n:root:not([data-theme]) {\n${dark}\n}\n}\n@media print {\n:root, :root[data-theme] {\n${light}\n}\n}\n`;
const { format } = await import("prettier");
const output = await format(css, { parser: "css" });
const path = "src/styles/tokens.generated.css";
if (process.argv.includes("--check")) {
  if ((await readFile(path, "utf8")) !== output)
    throw new Error("Generated tokens are stale. Run npm run tokens:build");
} else await writeFile(path, output);

const manifestPath = "design-system/tokens/resolved.generated.json";
const manifest = JSON.stringify(values, null, 2) + "\n";
if (process.argv.includes("--check")) {
  if ((await readFile(manifestPath, "utf8")) !== manifest)
    throw new Error("Token manifest is stale");
} else await writeFile(manifestPath, manifest);
